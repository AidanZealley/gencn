// Writes src/demo/themes.css: real shadcn themes for the landing demo,
// fetched from the same endpoint `shadcn init` and ui.shadcn.com/create use.
// Each theme comes in light and dark; the demo follows the visitor's
// colour scheme so it blends into the page around it. Run with `node scripts/themes.ts` after changing the list; the output is
// committed, so builds don't need the network.
import { writeFileSync } from 'node:fs'

type Theme = {
  name: string
  baseColor: string
  theme: string
  radius: string
  font: string
}

// Keep in step with `themes` in src/demo/script.ts (names and fonts).
const themes: Theme[] = [
  {
    name: 'neutral',
    baseColor: 'neutral',
    theme: 'neutral',
    radius: 'default',
    font: "'Geist Variable'",
  },
  {
    name: 'blue',
    baseColor: 'zinc',
    theme: 'blue',
    radius: 'small',
    font: "'Inter Variable'",
  },
  {
    name: 'orange',
    baseColor: 'stone',
    theme: 'orange',
    radius: 'large',
    font: "'Figtree Variable'",
  },
  {
    name: 'emerald',
    baseColor: 'mist',
    theme: 'emerald',
    radius: 'none',
    font: "'Geist Mono Variable'",
  },
]

const blocks: string[] = []
for (const theme of themes) {
  const query = new URLSearchParams({
    base: 'base',
    style: 'nova',
    baseColor: theme.baseColor,
    theme: theme.theme,
    iconLibrary: 'lucide',
    font: 'geist',
    rtl: 'false',
    menuAccent: 'subtle',
    menuColor: 'default',
    radius: theme.radius,
  })
  const response = await fetch(`https://ui.shadcn.com/init?${query}`)
  if (!response.ok) throw new Error(`${theme.name}: ${response.status}`)
  const { cssVars } = (await response.json()) as {
    cssVars: { light: Record<string, string>; dark: Record<string, string> }
  }
  for (const mode of ['light', 'dark'] as const) {
    // Dark vars leave out radius; it comes from light.
    const vars = { ...cssVars.light, ...cssVars[mode] }
    blocks.push(
      [
        `/* baseColor ${theme.baseColor}, theme ${theme.theme}, radius ${theme.radius}, ${mode} */`,
        // Dark also matches a swatch wearing a theme inside a dark page.
        mode === 'dark'
          ? `.dark[data-theme='${theme.name}'],\n.dark [data-theme='${theme.name}'] {`
          : `[data-theme='${theme.name}'] {`,
        `  color-scheme: ${mode};`,
        `  --app-font: ${theme.font}, sans-serif;`,
        ...Object.entries(vars).map(([key, value]) => `  --${key}: ${value};`),
        '}',
      ].join('\n'),
    )
  }
}

writeFileSync(
  new URL('../src/demo/themes.css', import.meta.url),
  `/* Generated by scripts/themes.ts from ui.shadcn.com/init. */\n\n${blocks.join('\n\n')}\n`,
)
console.log(`Wrote ${themes.length} themes.`)
